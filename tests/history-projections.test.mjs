import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = file => readFileSync(file,'utf8');
const history=read('server/src/history/history.service.ts');
const admin=read('server/src/saas-admin/saas-admin.controller.ts');
const owner=read('server/src/account/account-runtime.controller.ts');
const module=read('server/src/saas-admin/saas-admin.module.ts');
const platformMethod = history.split('async listPlatform(')[1]?.split('async asOf(')[0] || '';
assert.ok(platformMethod);
assert.match(platformMethod,/FROM "CommercialAuditEvent"/);
assert.match(platformMethod,/platformActivityEvent\.findMany/);
assert.doesNotMatch(platformMethod,/BusinessHistoryEvent|AccountHistoryEvent/);
assert.match(history,/async listAccount/);
assert.match(history,/subjectAccountId: accountId/);
assert.match(history,/return \[\.\.\.owned, \.\.\.authFacts\]/);
assert.match(admin,/@UseGuards\(JwtAuthGuard, PlatformAdminGuard\)/);
assert.match(admin,/@Get\('history'\)/);
assert.match(owner,/@UseGuards\(AccountGuard\)\s+@Get\('history'\)/);
assert.match(module,/HistoryModule/);
console.log('PASS: platform, tenant and User views are owner-filtered projections of canonical sources');
