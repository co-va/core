import assert from 'node:assert/strict';
import { parseEvidence, scopeFor, verifyEvidence } from '../scripts/check-release-evidence.mjs';
const path='server/src/data-transfer/contact-import.service.ts';
const entry={kind:'implemented',files:[path],criteria:['contacts.core'],result:'Reviewed import',remaining:'Owner acceptance pending',checks:['contact import test PASS']};
const msg=x=>'Operational-Evidence: '+JSON.stringify(x);
const run=(commits,versions,files=[path])=>verifyEvidence({files,commits,head:'head',versionAt:(sha,p)=>versions[sha]?.[p]??''});
const c={sha:'a',message:msg(entry)};
assert.equal(run([c],{a:{[path]:'x'},head:{[path]:'x'}}).errors.length,0);
assert.equal(run([c],{a:{[path]:'x'},head:{[path]:'y'}}).errors.length,1);
assert.equal(run([],{head:{[path]:'x'}}).errors.length,1);
assert.equal(run([{sha:'a',message:msg({...entry,criteria:['platform']})}],{a:{[path]:'x'},head:{[path]:'x'}}).errors.length,1);
assert.equal(run([{sha:'a',message:msg({...entry,criteria:['loyalty.balances']})}],{a:{[path]:'x'},head:{[path]:'x'}}).errors.length,1);
assert.throws(()=>parseEvidence(msg({...entry,criteria:['invented']})));
assert.throws(()=>parseEvidence(msg({...entry,ownerConfirmed:true})));
assert.throws(()=>parseEvidence(msg({...entry,checks:[]})));
assert.equal(run([c],{a:{[path]:'x'},head:{} }).errors.length,1);
assert.equal(run([c],{a:{},head:{}}).errors.length,0);
assert.equal(run([],{head:{}},['PROJECT_STATE.md']).errors.length,0);
assert.equal(scopeFor('admin/index.html').generated,true);
assert.equal(scopeFor('server/src/new-domain/a.ts').allowed.includes('platform'),false);
console.log('Release evidence gate: PASS');
