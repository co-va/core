import assert from 'node:assert/strict';
import { developmentProgress, criterionView, developmentMarkup } from '../admin/development-map.js';
const row=(key,status,deferred=false)=>({key,status,deferred});
assert.deepEqual(developmentProgress([row('a','ready'),row('a','ready'),row('b','pending')]),{status:'working',percent:50});
assert.deepEqual(developmentProgress([row('a','ready'),row('b','unfinished')]),{status:'unfinished',percent:50});
assert.deepEqual(developmentProgress([row('a','ready')]),{status:'ready',percent:100});
assert.deepEqual(developmentProgress([row('a','notStarted')]),{status:'notStarted',percent:0});
assert.deepEqual(developmentProgress([row('a','unknown')]),{status:null,percent:null});
assert.deepEqual(developmentProgress([row('a','pending')]),{status:'working',percent:null});
assert.deepEqual(developmentProgress([row('a','ready')],false),{status:null,percent:null});
assert.equal(developmentProgress([row('a','pending',true)]),null);
assert.deepEqual(developmentProgress([row('a','ready'),row('b','unknown',true)]),{status:'working',percent:50});
const sha='a'.repeat(40), c={key:'example',title:'Example'};
const ev=(kind,extra={})=>({id:kind,date:'2026-11-24',criterion:'example',kind,result:'Result',remaining:'',ownerConfirmed:true,versions:{core:sha},checks:['test'],...extra});
const snapshot=operationalProgress=>({registry:{operationalProgress}});
assert.equal(criterionView(c,snapshot([ev('not-started')])).status,'notStarted');
assert.equal(criterionView(c,snapshot([ev('accepted')])).status,'ready');
assert.equal(criterionView(c,snapshot([ev('accepted'),ev('candidate',{remaining:'Verify'})])).status,'pending');
assert.equal(criterionView(c,snapshot([ev('accepted'),ev('regression',{environment:'deployed',remaining:'Fix'})])).status,'unfinished');
assert.equal(criterionView(c,snapshot([ev('deferred')])).deferred,true);
const markup=developmentMarkup({activity:'services',open:new Set(['group:workspace','mechanism:workspace']),snapshot:snapshot([])},String);
assert.match(markup,/development-progress-track/);
assert.doesNotMatch(markup,/Частично готово|Уточнить приёмку<\/span>|Отложено по решению владельца/);
console.log('Development readiness progress: PASS');

// Additional checks: an audit finding is not a proven failure; optional failures do not label the whole group red.
const preliminary={key:'example',title:'Example',work:{state:'finish',finding:'Existing implementation; not fully verified',next:'Verify'}};
assert.equal(criterionView(preliminary,snapshot([])).status,'pending');
assert.equal(criterionView(c,snapshot([]),[{scenarios:[{id:'pass',criteria:['example'],state:'passed',title:'Functional check'}]}]).status,'partial');
assert.equal(criterionView(c,snapshot([]),[{scenarios:[{id:'batch',criteria:['example'],state:'failed',step:'Domain regression tests',title:'Batch'}]}]).status,'pending');
assert.equal(criterionView(c,snapshot([]),[{scenarios:[{id:'specific',criteria:['example'],state:'failed',step:'Specific functional check',title:'Specific failure'}]}]).status,'unfinished');
assert.deepEqual(developmentProgress([row('a','ready'),{...row('b','unfinished'),blocking:false}]),{status:'working',percent:50});
assert.deepEqual(developmentProgress([row('a','unknown'),{...row('b','unfinished'),blocking:false}]),{status:'working',percent:null});
const previouslyAccepted={...snapshot([]),mechanisms:[{rows:[{key:'records.prof',state:'accepted'}]}]};
assert.equal(criterionView({key:'records.prof',title:'Journal'},previouslyAccepted).status,'ready');
const unverifiedMarkup=developmentMarkup({activity:'services',snapshot:snapshot([])},String);
assert.doesNotMatch(unverifiedMarkup,/Требует доработки/);
console.log('Development readiness evidence classification: PASS');
