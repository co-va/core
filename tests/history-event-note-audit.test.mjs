import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(path, 'utf8');
const migration = read('server/prisma/migrations/20261106231000_tenant_event_note_history/migration.sql');
const actor = read('server/src/history/history-actor.ts');
const history = read('server/src/history/history.service.ts');
const event = read('server/src/event/event.service.ts');
const note = read('server/src/note/note.service.ts');
assert.match(migration, /"professional_history_write"\(/);
assert.doesNotMatch(migration, /CREATE TABLE/i);
for (const entity of ['Event', 'Note']) assert.match(migration, new RegExp('AFTER INSERT OR UPDATE OR DELETE ON "' + entity + '"'));
assert.match(migration, /IF tenant_key = '' THEN RETURN NULL/);
assert.match(migration, /'before', to_jsonb\(OLD\), 'after', to_jsonb\(NEW\)/);
assert.match(migration, /'deleted', to_jsonb\(OLD\)/);
assert.match(actor, /set_config\('co_va.history_actor_id'/);
assert.match(actor, /set_config\('co_va.history_correlation_id'/);
assert.match(actor, /prisma\.\$transaction\(async tx/);
assert.match(event, /withTenantHistoryActor\(this\.prisma, actor/);
assert.match(note, /withTenantHistoryActor\(this\.prisma, actor/);
assert.match(history, /"entityType" <> 'note'/);
assert.match(history, /p\."platformAccountId" = \$\{platformAccountId\}/);
console.log('PASS: canonical Event/Note History, actor, tenant/private isolation');
