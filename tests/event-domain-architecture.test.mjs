import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = (path) => fs.readFileSync(path, 'utf8');
const schema = read('server/prisma/schema.prisma');
const migration = read('server/prisma/migrations/20261022180000_canonical_event/migration.sql');
const creation = read('journal/creation-flow.js');
const eventCreation = read('journal/event-create.js');
const eventView = read('journal/event-view.js');
const source = read('journal/time-usage-source.js');
const day = read('journal/день.js');
const timeline = read('ui/time/journal-day.js');
const operational = read('core/runtime/operational-state.js');
const businessRuntime = read('core/runtime/business-state.js');
const records = read('core/records/records.js');
assert.match(schema, /model Event \{/);
for (const field of ['id','ownerType','ownerId','context','date','from','to','title','description','color','workplaceId','createdAt','updatedAt']) assert.match(schema, new RegExp(`\\b${field}\\b`));
assert.match(migration, /jsonb_array_elements[\s\S]*?'breaks'/);
assert.match(migration, /'Перерыв'/);
assert.match(migration, /ON CONFLICT \("id"\) DO NOTHING/);
assert.match(migration, /RAISE EXCEPTION 'legacy Break migration incomplete/);
assert.match(migration, /- 'breaks'/);
assert.match(creation, /label: 'Событие'/);
assert.match(creation, /activeMode = 'record'/);
assert.doesNotMatch(creation, /break-create|Занять время/);
assert.match(eventCreation, /createEvent/);
assert.match(eventCreation, /timeHint/);
assert.match(eventCreation, /openTimeRangeAction/);
assert.match(eventCreation, /colorPicker/);
assert.match(eventView, /excludeId: eventId/);
assert.match(eventView, /updateEvent\(eventId/);
assert.match(eventView, /removeEvent\(eventId/);
assert.match(source, /type: 'event'/);
assert.doesNotMatch(source, /type: 'break'|break-read|break-service/);
assert.match(day, /usage\?\.type === 'event'/);
assert.match(day, /openEventView/);
assert.match(timeline, /journal-record--event/);
assert.match(businessRuntime, /apiRequest\('\/events'\)/);
assert.match(businessRuntime, /hydrateEventsFromServer/);
assert.doesNotMatch(operational, /break-data|hydrateBreaksFromServer|queueOperationalDataset\('breaks'/);
assert.doesNotMatch(records, /createEvent|createJournalBreak/);
for (const path of ['journal/break-data.js','journal/break-read.js','journal/break-service.js','journal/break-view.js','journal/break-create.js']) assert.equal(fs.existsSync(path), false, `${path} must be removed`);
console.log('Event domain architecture test passed.');
