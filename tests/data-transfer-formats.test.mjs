import assert from 'node:assert/strict';
import fs from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const code = stripTypeScriptTypes(fs.readFileSync('server/src/data-transfer/formats.ts','utf8'));
const { calendarDate, clock, decimal, parseCsv, canonical } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
assert.equal(calendarDate('15.05.2024'),'2024-05-15');
assert.equal(calendarDate('2024-05-15 00:00'),'2024-05-15');
assert.equal(calendarDate(45427),'2024-05-15');
assert.equal(calendarDate(45427.625),'2024-05-15');
assert.throws(()=>calendarDate('2024-02-30'), /Неверная дата/);
assert.throws(()=>calendarDate('15.05.2024 14:15'), /Неверная дата/);
assert.throws(()=>calendarDate(60), /Неверная дата/);
assert.equal(clock('9:30'),'09:30'); assert.equal(clock(0),'00:00'); assert.equal(clock(''),'');
assert.throws(()=>clock('25:30'), /Неверное время/);
assert.equal(decimal('10 000,50','Сумма'),10000.5); assert.throws(()=>decimal('10руб','Сумма'), /неверный формат/);
assert.deepEqual(parseCsv('\uFEFFИмя;Примечание\r\n"Анна";"два; слова\nна строках"\r\n'), [['Имя','Примечание'],['Анна','два; слова\nна строках']]);
assert.throws(()=>parseCsv('a;"x'), /кавычки/);
assert.equal(canonical({b:1,a:2}),canonical({a:2,b:1}));
// Run the canonical Person domain matching rules without Nest/database dependencies.
let matching=fs.readFileSync('server/src/business-state/person-transfer.ts','utf8').replace(/^import .*\n/gm,'');
matching=stripTypeScriptTypes(matching);
const { normalizePhone }=await import('../core/phone/index.js'); const {normalizeUEI}=await import('../core/uei-format.js');
const resolve=new Function('normalizePhone','normalizeUEI',matching.replace('export function resolveTransferredPerson','function resolveTransferredPerson')+'\nreturn resolveTransferredPerson;')(normalizePhone,normalizeUEI);
const anna={key:'a',name:'Анна',phones:['+79991234567'],emails:['one@example.test']};
assert.equal(resolve([anna],{}, {phone:'89991234567',name:'Анна'}).person.key,'a');
assert.throws(()=>resolve([anna],{}, {phone:'79991234567',name:'Аня'}), /В импортируемых данных указано имя Аня/);
assert.throws(()=>resolve([anna],{relations:{'person:a':'0012'}}, {phone:'79991234567',name:'Анна',uei:'315'}), /Сохранён UEI 0012/);
assert.equal(resolve([anna],{}, {phone:'79991234567',name:'Анна',uei:'12'}).uei,'0012');
assert.equal(resolve([anna],{}, {phone:'79997654321',name:'Мария',email:'one@example.test'}).person,null);
assert.equal(resolve([anna],{}, {email:'different@example.test',name:'Анна'}).person,null);
assert.throws(()=>resolve([anna],{}, {email:'one@example.test',name:'Анна'}), /Email уже используется/);
console.log('Data transfer format and person conflicts: OK');
