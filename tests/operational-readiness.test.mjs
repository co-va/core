import assert from 'node:assert/strict';
import { MECHANISMS, coverageSnapshot, closureEvidence, loadOperationalReadiness, readinessMarkup, CORE_SCENARIOS, coreAuditSnapshot, loadCoreAudit, USER_SCENARIOS, userAuditSnapshot, professionalAuditSnapshot, evidenceCoverage, loadUserAudit, workQueue } from '../admin/operational-readiness.js';
const sha='a'.repeat(40);
const item={id:'start.service',paths:['core/service/**'],requires:[],external:[],acceptance:{visual:'approved',data:'approved'},closure:{state:'locked',baselineSha:sha,approvedBy:'owner',approvedAt:'2026-11-22',evidence:['test']}};
const registry={schemaVersion:1,repository:'co-va/professional',branch:'staging',items:[item]};
const same={status:'identical',files:[]}, change={status:'ahead',files:[{filename:'core/service/editor.js'}]};
assert.equal(MECHANISMS.length,18);
const a=coverageSnapshot(registry,{[sha]:same});
assert.equal(a.confirmed,1,'Shared catalogue criterion is counted once');
assert.equal(a.currentConfirmed,1);
assert.equal(a.mechanisms.find(m=>m.id==='services').confirmed,1);
assert.equal(a.mechanisms.find(m=>m.id==='products').confirmed,1);
const b=coverageSnapshot(registry,{[sha]:change});
assert.equal(b.confirmed,a.confirmed,'Candidate update does not erase acceptance');
assert.equal(b.currentConfirmed,0);
assert.equal(b.changed,1);
assert.equal(coverageSnapshot(registry,{}).unverified,1,'Missing comparison is not a pass');
assert.equal(coverageSnapshot({...registry,items:[{...item,closure:{...item.closure,evidence:[]}}]},{}).confirmed,0);
assert.equal(coverageSnapshot({...registry,items:[{...item,closure:{...item.closure,state:'verifying'}}]},{}).confirmed,0);
assert.throws(()=>coverageSnapshot({...registry,items:[item,item]}));
assert.equal(closureEvidence({...item,external:['Core']},same,new Map()).state,'unverified');
const requests=[];
const loaded=await loadOperationalReadiness(async url=>{requests.push(url);return {ok:true,json:async()=>url.includes('/git/ref/')?{object:{sha}}:registry};});
assert.equal(loaded.sha,sha);
assert.equal(loaded.confirmed,1);
assert.equal(requests.length,2);
assert.ok(requests[1].includes(sha));
const markup=readinessMarkup(loaded,String,'services');
assert.match(markup,/Операционная готовность/);
assert.match(markup,/start.service/);
assert.doesNotMatch(markup,/<input/);
assert.match(readinessMarkup(null,String),/Проценты не определены/);
console.log('Operational coverage projection: PASS');

// Owner-approved 24.11: development map is a separate Admin navigation section, not an Overview panel.
const adminSource = (await import('node:fs')).readFileSync(new URL('../admin/admin.js', import.meta.url), 'utf8');
const overview = adminSource.slice(adminSource.indexOf('function renderOverview()'),adminSource.indexOf('function openDeleteTenantModal('));
assert.match(adminSource, /\{ id: 'operational-readiness', label: 'Карта развития'/);
assert.doesNotMatch(overview, /data-overview-section="operational-readiness"/);
assert.match(adminSource, /return renderDevelopmentMap\(content,/);

// Core evidence is independent from owner acceptance, validated against exact SHA and successful named steps.
const run={id:42,head_sha:sha,path:'.github/workflows/check.yml'};
const pkg={scripts:{test:CORE_SCENARIOS.filter(s=>s.test).map(s=>'node '+s.test).join(' && ')}};
const workflow=[...new Map(CORE_SCENARIOS.map(s=>[s.step,'- name: '+s.step+'\n  run: '+s.command])).values()].join('\n');
const jobs=['check','staging-smoke'].map((name,i)=>({id:i+1,name,head_sha:sha,conclusion:'success',steps:[...new Set(CORE_SCENARIOS.filter(s=>s.job===name).map(s=>s.step))].map(name=>({name,conclusion:'success'}))}));
const core=coreAuditSnapshot(sha,run,jobs,pkg,workflow);
assert.equal(core.passed,CORE_SCENARIOS.length);
assert.equal(coreAuditSnapshot(sha,run,jobs,{scripts:{test:''}},workflow).passed,CORE_SCENARIOS.filter(s=>!s.test).length);
assert.equal(coreAuditSnapshot(sha,run,[],pkg,workflow).passed,0);
assert.equal(coreAuditSnapshot(sha,run,jobs,pkg,'').passed,0);
assert.throws(()=>coreAuditSnapshot(sha,{...run,head_sha:'b'.repeat(40)},jobs,pkg,workflow));
const failing=jobs.map(j=>j.name==='staging-smoke'?{...j,conclusion:'failure',steps:j.steps.map(s=>({...s,conclusion:'failure'}))}:j);
assert.ok(coreAuditSnapshot(sha,run,failing,pkg,workflow).failed>0);
assert.equal(a.confirmed,1,'Core evidence cannot inflate full acceptance');
assert.match(readinessMarkup(loaded,String,'contacts',core),/Подключённые сценарии Core/);
assert.match(readinessMarkup(loaded,String,'contacts',core),/Импорт контактов: повторы/);
const loadedCore=await loadCoreAudit(async url=>({ok:true,json:async()=>url.includes('/git/ref/')?{object:{sha}}:url.includes('/check-runs')?{check_runs:[{id:1,name:'check',head_sha:sha,app:{slug:'github-actions'},details_url:'https://github.com/co-va/core/actions/runs/42/job/1'}]}:url.includes('/jobs?')?{jobs}:url.endsWith('/package.json')?pkg:run,text:async()=>workflow}));
assert.equal(loadedCore.passed,CORE_SCENARIOS.length);
console.log('Core CI evidence projection: PASS');

// User: the exact released tree, named workflow and actual step are required.
const userWorkflow=[...new Map(USER_SCENARIOS.map(s=>[s.step,'- name: '+s.step+'\n  run: node '+s.script])).values()].join('\n');
const userJobs=[{id:2,name:'check',head_sha:sha,conclusion:'success',steps:[...new Set(USER_SCENARIOS.map(s=>s.step))].map(name=>({name,conclusion:'success'}))}];
const user=userAuditSnapshot(sha,run,userJobs,userWorkflow);
assert.equal(user.passed,USER_SCENARIOS.length);
assert.equal(userAuditSnapshot(sha,run,userJobs,'').passed,0);
assert.throws(()=>userAuditSnapshot(sha,{...run,head_sha:'b'.repeat(40)},userJobs,userWorkflow));
const prof=professionalAuditSnapshot(registry,sha,a);
assert.equal(prof.passed,1);
assert.equal(prof.historical,0);
const historical=professionalAuditSnapshot({...registry,items:[...registry.items,{id:'journal.graph',closure:{state:'verifying',evidence:['Historical test']}}]},sha,a);
assert.equal(historical.historical,1);
const evidence=evidenceCoverage(a,core,user,historical);
assert.equal(evidence.total,44);
assert.ok(evidence.supported>1 && evidence.supported<44);
assert.equal(evidenceCoverage(a,core,user,historical,historical).supported,evidence.supported);
assert.match(readinessMarkup(loaded,String,'records',core,user),/User\/main: 4 \/ 4/);
assert.match(readinessMarkup(loaded,String,'records',core,user),/Критерии с доказательствами/);
const userLoaded=await loadUserAudit(async url=>({ok:true,json:async()=>url.includes('/git/ref/')?{object:{sha}}:url.includes('/actions/runs?')?{workflow_runs:[run]}:{jobs:userJobs},text:async()=>userWorkflow}));
assert.equal(userLoaded.passed,4);
console.log('Cross-repository evidence projection: PASS');

