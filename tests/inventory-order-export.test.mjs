import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const service = readFileSync('server/src/inventory/inventory-order-export.service.ts','utf8');
const controller = readFileSync('server/src/inventory/inventory.controller.ts','utf8');
const moduleSource = readFileSync('server/src/inventory/inventory.module.ts','utf8');
assert.match(controller, /@Get\('orders\/:orderId\/export\/:format'\)/);
assert.match(controller, /supplierDocument\(request\.auth!\.tenantId, orderId\)/);
assert.match(controller, /format === 'pdf'/);
assert.match(controller, /Cache-Control', 'private, no-store'/);
assert.match(moduleSource, /providers: \[[^\]]*InventoryOrderExportService/);
assert.match(service, /tenantId, orderId/);
assert.match(service, /orderBy: \{ position: 'asc' \}/);
assert.match(service, /article: articles\.get\(line\.itemId\) \|\| ''/);
assert.match(service, /name: String\(line\.name \|\| ''\)/);
assert.match(service, /packages: Number\(line\.packages\)/);
assert.match(service, /const COLUMN_TITLES = \['Артикул', 'Наименование', 'Количество, шт\.'\]/);
assert.match(service, /article: line\.article \|\| null/);
assert.match(service, /name: line\.name \|\| null/);
assert.doesNotMatch(service, /containerCount|balance|cost|price|position:\s*line\.position/);
assert.match(service, /doc\.font\(FONT\)/);
console.log('PASS: saved order PDF/XLSX tenant scope, exactly 3 supplier columns, empty values preserved');
